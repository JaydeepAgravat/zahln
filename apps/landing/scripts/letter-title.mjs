// Sets "Die Zahln Edition" in Inter Tight 800 and converts it to SVG paths (opentype.js), so the title is
// our own lettering: tight, optically kerned, drawable stroke by stroke (pathLength=1) on Day 10.
// The font is fetched from Google Fonts' static TTF (SIL OFL 1.1) into a temp folder, never committed.
// Output: lib/lettering.gen.ts. Usage: node scripts/letter-title.mjs
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import opentype from 'opentype.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const cacheDir = join(tmpdir(), 'zahln-landing-fonts');
await mkdir(cacheDir, { recursive: true });
const ttf = join(cacheDir, 'InterTight-800.ttf');

async function fontBuffer() {
  try {
    return await readFile(ttf);
  } catch {
    // No browser UA → Google Fonts serves plain TTF URLs.
    const css = await (await fetch('https://fonts.googleapis.com/css2?family=Inter+Tight:wght@800')).text();
    const url = css.match(/url\((https:\/\/fonts\.gstatic\.com\/[^)]+\.ttf)\)/)?.[1];
    if (!url) throw new Error('No TTF URL in Google Fonts CSS');
    const buf = Buffer.from(await (await fetch(url)).arrayBuffer());
    await writeFile(ttf, buf);
    return buf;
  }
}

const buf = await fontBuffer();
const font = opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength));
const SIZE = 100;
const TRACKING = -0.035 * SIZE; // −3.5 %

/** One path per word, laid out on its own line, left-aligned at x = 0. */
function word(text, baseline) {
  let x = 0;
  const glyphs = [...text].map((c) => font.charToGlyph(c)); // per char: opentype.js trips on this font's ccmp lookups
  const parts = [];
  glyphs.forEach((g, i) => {
    const p = g.getPath(x, baseline, SIZE);
    parts.push({ char: text[i], d: p.toPathData(2), box: p.getBoundingBox() });
    const next = glyphs[i + 1];
    x += (g.advanceWidth / font.unitsPerEm) * SIZE + TRACKING;
    if (next) x += (font.getKerningValue(g, next) / font.unitsPerEm) * SIZE;
  });
  return { text, width: x - TRACKING, parts };
}

const lineHeight = SIZE * 0.92;
const first = SIZE * 0.74;
// Extra room under "Zahln" for the swash that runs out of the Z's base.
const GAP = 16;

function title(firstWord) {
  const lines = [
    word(firstWord, first),
    word('Zahln', first + lineHeight),
    word('Edition', first + lineHeight * 2),
  ];
  const width = Math.ceil(Math.max(...lines.map((l) => l.width)));
  const height = Math.ceil(first + lineHeight * 2 + GAP + SIZE * 0.06);
  // The Z of "Zahln": its bounding box anchors the hand-drawn ember swash (components/Lettering.tsx).
  const z = lines[1].parts[0].box;
  return {
    viewBox: `0 0 ${width} ${height}`,
    width,
    height,
    words: lines.map((l) => ({ text: l.text, d: l.parts.map((p) => p.d).join('') })),
    z: { x1: Math.round(z.x1), y1: Math.round(z.y1), x2: Math.round(z.x2), y2: Math.round(z.y2) },
  };
}

const out = { de: title('Die'), en: title('The') };
await writeFile(
  join(root, 'lib/lettering.gen.ts'),
  `// Generated by scripts/letter-title.mjs (Inter Tight 800, SIL OFL 1.1). Do not edit.\nexport const lettering = ${JSON.stringify(out, null, 2)} as const;\n`,
);
process.stdout.write(`lettering de ${out.de.viewBox}, en ${out.en.viewBox}, Z ${JSON.stringify(out.de.z)}\n`);
