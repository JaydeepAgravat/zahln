// Repeatable art treatment: art-src/<slug>.jpg → public/art/<slug>-{l,p}-<w>.{avif,webp} + lib/art.gen.ts.
// For each painting: trim the frame edge, crop to 16:10 (landscape, desktop) and 9:16 (portrait, mobile)
// around a focal point, grade toward ink shadows and ember highlights, add fine grain, and export AVIF + WebP
// at 640/960/1280/2048 (portrait: 640/960/1280) plus a tiny blurred placeholder.
// Usage: node scripts/grade-art.mjs   (after scripts/fetch-art.mjs)
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const manifest = JSON.parse(await readFile(join(root, 'scripts/art-manifest.json'), 'utf8'));
const outDir = join(root, 'public/art');
await mkdir(outDir, { recursive: true });

const CROPS = {
  l: { ratio: 16 / 10, widths: [640, 960, 1280, 2048] },
  p: { ratio: 9 / 16, widths: [640, 960, 1280] },
};

/** The largest rect of the given ratio inside (w, h), centred on the focal point and clamped to the image. */
function cropRect(w, h, ratio, [fx, fy]) {
  let cw = w;
  let ch = Math.round(w / ratio);
  if (ch > h) {
    ch = h;
    cw = Math.round(h * ratio);
  }
  const left = Math.min(Math.max(Math.round(fx * w - cw / 2), 0), w - cw);
  const top = Math.min(Math.max(Math.round(fy * h - ch / 2), 0), h - ch);
  return { left, top, width: cw, height: ch };
}

/** Ember highlight in the upper right, ink vignette at the edges. Blended soft-light, so it grades, not tints. */
function gradeOverlay(width, height) {
  return Buffer.from(`<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}">
    <defs>
      <radialGradient id="e" cx="78%" cy="18%" r="70%"><stop offset="0" stop-color="#FF4F1F" stop-opacity=".55"/><stop offset="1" stop-color="#FF4F1F" stop-opacity="0"/></radialGradient>
      <radialGradient id="v" cx="50%" cy="45%" r="75%"><stop offset=".55" stop-color="#1B1A17" stop-opacity="0"/><stop offset="1" stop-color="#1B1A17" stop-opacity=".85"/></radialGradient>
    </defs>
    <rect width="100%" height="100%" fill="url(#e)"/><rect width="100%" height="100%" fill="url(#v)"/>
  </svg>`);
}

// biome-ignore lint/correctness/noUnusedVariables: kept for print/OG exports
async function grain(width, height) {
  const noise = await sharp({
    create: {
      width,
      height,
      channels: 3,
      background: '#808080',
      noise: { type: 'gaussian', mean: 128, sigma: 26 },
    },
  })
    .greyscale()
    .png()
    .toBuffer();
  // 8 % alpha so the grain is felt rather than seen.
  return sharp(noise).ensureAlpha(0.08).png().toBuffer();
}

const gen = {};
for (const item of manifest) {
  const src = sharp(join(root, `art-src/${item.slug}.jpg`));
  const meta = await src.metadata();
  const tx = Math.round(meta.width * item.trim);
  const ty = Math.round(meta.height * item.trim);
  const trimmed = { left: tx, top: ty, width: meta.width - 2 * tx, height: meta.height - 2 * ty };
  const entry = { slug: item.slug };
  for (const [key, crop] of Object.entries(CROPS)) {
    const rect = cropRect(trimmed.width, trimmed.height, crop.ratio, key === 'l' ? item.land : item.port);
    const base = await sharp(join(root, `art-src/${item.slug}.jpg`))
      .extract({ ...rect, left: trimmed.left + rect.left, top: trimmed.top + rect.top })
      .resize({ width: Math.min(rect.width, crop.widths.at(-1)) })
      .modulate({ saturation: 0.82, brightness: 0.94 })
      .linear(1.06, -6)
      .toBuffer({ resolveWithObject: true });
    const { width, height } = base.info;
    const graded = await sharp(base.data)
      // No baked-in grain: noise is incompressible (it doubled the AVIF sizes) and the page adds grain on top
      // anyway (CSS .grain overlay, or the shader). grain() is kept for print/OG exports.
      .composite([{ input: gradeOverlay(width, height), blend: 'soft-light' }])
      .toBuffer();
    for (const w of crop.widths) {
      const h = Math.round(w / crop.ratio);
      const img = sharp(graded).resize(w, h, { fit: 'cover' });
      await img
        .clone()
        .avif({ quality: 40, effort: 5 })
        .toFile(join(outDir, `${item.slug}-${key}-${w}.avif`));
      await img
        .clone()
        .webp({ quality: 64 })
        .toFile(join(outDir, `${item.slug}-${key}-${w}.webp`));
    }
    const blur = await sharp(graded).resize(16).blur(1).webp({ quality: 40 }).toBuffer();
    entry[key] = {
      widths: crop.widths,
      ratio: crop.ratio,
      blur: `data:image/webp;base64,${blur.toString('base64')}`,
    };
  }
  gen[item.use] = entry;
  process.stdout.write(`graded ${item.slug}\n`);
}

await writeFile(
  join(root, 'lib/art.gen.ts'),
  `// Generated by scripts/grade-art.mjs. Do not edit.\nexport const art = ${JSON.stringify(gen, null, 2)} as const;\n`,
);
