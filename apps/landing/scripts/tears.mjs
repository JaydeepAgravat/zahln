// Writes app/tears.gen.css: the torn-receipt edges as CSS mask classes, generated once from lib/tornEdge.ts.
// Keeping them in the (cached, shared) stylesheet instead of inline styles keeps ~20 KB of path data out of
// every HTML page and its RSC payload. Deterministic: same seeds → same file.
// Usage: node scripts/tears.mjs   (Node ≥ 22.18 strips the types from the .ts import)
import { writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { TEAR_SEEDS, TEAR_SIZE } from '../lib/tears.ts';
import { tornEdgeMask } from '../lib/tornEdge.ts';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
let css = '/* Generated by scripts/tears.mjs from lib/tornEdge.ts. Do not edit. */\n';
TEAR_SEEDS.forEach((seed, i) => {
  // One shape per variant; the bottom tear is the same mask mirrored (see .tear-bottom in globals.css).
  const mask = tornEdgeMask(seed, TEAR_SIZE.width, TEAR_SIZE.amplitude, {
    paper: 'bottom',
    tooth: TEAR_SIZE.tooth,
  });
  css += `.tear-v${i}{-webkit-mask-image:${mask};mask-image:${mask}}\n`;
});
await writeFile(join(root, 'app/tears.gen.css'), css);
process.stdout.write(`tears: ${TEAR_SEEDS.length} variants, ${(css.length / 1024).toFixed(1)} KB\n`);
