const path = require('node:path');
const { getDefaultConfig, mergeConfig } = require('@react-native/metro-config');
const { withNativeWind } = require('nativewind/metro');

const projectRoot = __dirname;

// Build-time settings baked into the JS bundle (Metro doesn't inline process.env). Used for the LAN demo APK:
//   ZAHLN_API_URL=http://192.168.x.y:4000 ./gradlew assembleRelease -PlanHost=192.168.x.y
// Without it the file says null and the app uses the emulator/simulator default.
require('node:fs').writeFileSync(
  path.join(projectRoot, 'src/app/env.gen.js'),
  `// Generated by metro.config.js. Do not edit.\nexport const API_URL_OVERRIDE = ${JSON.stringify(process.env.ZAHLN_API_URL || null)};\n`,
);
const workspaceRoot = path.resolve(projectRoot, '../..');

/**
 * Monorepo setup: watch the whole workspace so `@zahln/shared` hot-reloads,
 * and resolve modules from the hoisted root node_modules (one copy of react / react-native).
 * @type {import('@react-native/metro-config').MetroConfig}
 */
const config = {
  watchFolders: [workspaceRoot],
  resolver: {
    nodeModulesPaths: [
      path.resolve(projectRoot, 'node_modules'),
      path.resolve(workspaceRoot, 'node_modules'),
    ],
    unstable_enablePackageExports: true,
  },
};

module.exports = withNativeWind(mergeConfig(getDefaultConfig(projectRoot), config), {
  input: './global.css',
});
