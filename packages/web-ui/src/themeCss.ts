import { type ColorScheme, type ColorToken, colors, radius, typeScale } from '@zaster/shared/tokens';

/** `textPrimary` → `text-primary` */
const kebab = (s: string) => s.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);
const tokens = Object.keys(colors.light) as ColorToken[];
const vars = (scheme: ColorScheme, indent: string) =>
  tokens.map((t) => `${indent}--color-${kebab(t)}: ${colors[scheme][t]};`).join('\n');

/**
 * The Tailwind 4 theme for every web surface, generated from `@zaster/shared/tokens` so the web and the
 * phones can't drift. `src/theme.css` is this function's output, checked by test/theme.test.ts;
 * `pnpm --filter @zaster/web-ui theme` regenerates it after a token change.
 *
 * Utilities read the variables (`bg-surface` → `var(--color-surface)`), so dark mode only swaps values:
 * from the OS by default, or forced with `data-theme` on <html>.
 */
export function themeCss(): string {
  const sizes = Object.entries(typeScale)
    .map(
      ([k, v]) =>
        `  --text-${kebab(k)}: ${v.size / 16}rem;\n  --text-${kebab(k)}--line-height: ${v.lineHeight / v.size};`,
    )
    .join('\n');
  const radii = Object.entries(radius)
    .map(([k, v]) => `  --radius-${k}: ${v}px;`)
    .join('\n');
  return `/* Generated by packages/web-ui/src/themeCss.ts from @zaster/shared/tokens. Do not edit. */
@theme {
  --color-*: initial;
  --color-transparent: transparent;
  --color-current: currentColor;
${vars('light', '  ')}
${radii}
${sizes}
  --font-sans: 'Inter Variable', ui-sans-serif, system-ui, sans-serif;
  --font-mono: ui-monospace, 'SF Mono', Menlo, monospace;
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme='light']) {
${vars('dark', '    ')}
  }
}

:root[data-theme='dark'] {
${vars('dark', '  ')}
}
`;
}
